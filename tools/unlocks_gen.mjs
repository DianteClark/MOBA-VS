// Regenerates src/data/unlocks-tiers.js (Koban price tiers) from a tools/scantiers.mjs result.
//   node tools/scan.mjs --from a.jsonl,b.jsonl --json scan.json
//   node tools/scantiers.mjs scan.json --force wu=Specialist --out tiers.json
//   node tools/unlocks_gen.mjs tiers.json [--note "focused re-check after the v24 balance pass"]
// Every hero in src/data/heroes.js must have a tier (a hero missing from the scan is an error: scan it first).
// The file is data only (one letter per hero plus its main role), so the Worker can import it cheaply.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const { HEROES, ROLES } = await import('../src/data/heroes.js');
const args = process.argv.slice(2), opt = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 ? args[i + 1] : d; };
const file = args.find((a, i) => !a.startsWith('--') && !(i && args[i - 1].startsWith('--')));
if (!file) { console.error('usage: node tools/unlocks_gen.mjs tiers.json [--note text]'); process.exit(1); }
const rows = JSON.parse(readFileSync(file, 'utf8'));
const LETTER = { General: 'G', Specialist: 'S', Expert: 'E', Legend: 'L' };
const by = Object.fromEntries(rows.map((r) => [r.id, r]));
const missing = HEROES.filter((h) => !by[h.id] || !LETTER[by[h.id].tier]).map((h) => h.id);
if (missing.length) { console.error('no tier for: ' + missing.join(', ')); process.exit(1); }
const lines = [];
for (const role of ROLES) {
  lines.push(`  // ${role}`);
  const list = HEROES.filter((h) => h.role === role).sort((a, b) => 'GSEL'.indexOf(LETTER[by[a.id].tier]) - 'GSEL'.indexOf(LETTER[by[b.id].tier]) || (a.id < b.id ? -1 : 1));
  for (let i = 0; i < list.length; i += 6) lines.push('  ' + list.slice(i, i + 6).map((h) => `${h.id}: ['${LETTER[by[h.id].tier]}', '${role}']`).join(', ') + ',');
}
const counts = {}; for (const h of HEROES) { const t = LETTER[by[h.id].tier]; counts[t] = (counts[t] || 0) + 1; }
const forced = rows.filter((r) => r.forced).map((r) => `${r.id}=${r.tier}`);
const src = `// GENERATED by tools/unlocks_gen.mjs from a tools/scantiers.mjs result: do not edit by hand.
// Koban price tier (G General, S Specialist, E Expert, L Legend) and main role of every hero.
// ${HEROES.length} heroes: ${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ')}.${forced.length ? ` Owner overrides: ${forced.join(', ')}.` : ''}
// ${opt('note', 'champion scan')}
export const HERO_TIER = {
${lines.join('\n')}
};
`;
const out = fileURLToPath(new URL('../src/data/unlocks-tiers.js', import.meta.url));
writeFileSync(out, src);
console.log(`wrote ${out}:`, counts);
