// Writes precache.json: every file the game needs to open and play vs AI with no connection. sw.js downloads
// the list into its cache after the first full load (the page asks, src/net/offline.js).
//   node tools/precache.mjs           rewrite precache.json
//   node tools/precache.mjs --check   exit 1 if it is out of date (run it after adding or removing files)
// Left out: the owner dashboard, music (streamed with range requests), language packs (the page adds its own),
// the i18n source catalog, dev pages, tools and the Worker.
import { readdirSync, statSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const DIRS = ['src', 'css', 'assets/img', 'assets/font', 'assets/audio/sfx'];
const FILES = ['./', 'manifest.webmanifest', 'favicon.ico', 'apple-touch-icon.png', 'apple-touch-icon-precomposed.png'];
const SKIP = /(^|\/)(admin[^/]*\.(js|css|html)|adminreplay\.js)$|^src\/i18n\/(en\.json|packs\/)|\.(md|map|txt)$|(^|\/)\./;
const KEEP = /\.(js|mjs|css|json|png|jpe?g|webp|gif|svg|ttf|woff2?|mp3|ogg|wav)$/i;

function walk(d) {
  const out = [];
  for (const f of readdirSync(join(ROOT, d)).sort()) {
    const p = d + '/' + f;
    if (statSync(join(ROOT, p)).isDirectory()) out.push(...walk(p));
    else if (KEEP.test(f) && !SKIP.test(p)) out.push(p);
  }
  return out;
}
const files = [...FILES.filter((f) => f === './' || existsSync(join(ROOT, f))), ...DIRS.flatMap(walk)];
const bytes = files.reduce((a, f) => a + (f === './' ? statSync(join(ROOT, 'index.html')).size : statSync(join(ROOT, f)).size), 0);
const json = JSON.stringify({ note: 'generated by tools/precache.mjs', files }, null, 0).replace(/","/g, '",\n"') + '\n';
const target = join(ROOT, 'precache.json');
if (process.argv.includes('--check')) {
  const cur = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (cur !== json) { console.log('precache.json is out of date: run node tools/precache.mjs'); process.exit(1); }
  console.log(`precache.json up to date: ${files.length} files, ${(bytes / 1048576).toFixed(1)} MB`);
} else {
  writeFileSync(target, json);
  console.log(`wrote precache.json: ${files.length} files, ${(bytes / 1048576).toFixed(1)} MB`);
}
